def parse(spec):
    if '|' in spec:
        a, b = spec.split('|')
        above = a.split('/')
        below = b.split('/')
    else:
        above = spec.split('/')
        below = []
    rows = above + below
    w = max(len(r) for r in rows)
    top = BASE - len(above) + 1
    pix = []
    for i, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == '#':
                pix.append((x, top + i))
    return w, pix


def build(outdir):
    chars = [' '] + sorted(G.keys(), key=lambda c: ord(c))
    SHEET_W = 256
    x = y = 0
    places = []
    glyphs = []
    for c in chars:
        if c == ' ':
            w, pix = 2, []
        else:
            w, pix = parse(G[c])
        if x + w > SHEET_W:
            x = 0
            y += CELL_H
        places.append((c, x, y, w))
        glyphs.append(pix)
        x += w + 1
    H = y + CELL_H
    img = Image.new('RGBA', (SHEET_W, H), (0, 0, 0, 0))
    px = img.load()
    for (c, gx, gy, w), pix in zip(places, glyphs):
        for (px_, py_) in pix:
            px[gx + px_, gy + py_] = (255, 255, 255, 255)
    img.save(outdir + '/font.png', optimize=True)
    with open(outdir + '/font.bin', 'wb') as f:
        f.write(struct.pack('>H', len(places)))
        for (c, gx, gy, w) in places:
            f.write(struct.pack('>HHBB', ord(c), gx, gy, w))
    return len(places), (SHEET_W, H)


if __name__ == '__main__':
    import sys
    print(build(sys.argv[1] if len(sys.argv) > 1 else '.'))
